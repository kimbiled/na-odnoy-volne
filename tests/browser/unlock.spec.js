import { test, expect } from '@playwright/test'
import { calmSequence } from '../../src/game.js'
import { installMediaClock } from './helpers/mediaClock.js'

test('49 points and an old unlock do not reveal the invitation; the 50th point opens video 2', async ({ page }) => {
  await installMediaClock(page)
  await page.addInitScript(() => {
    localStorage.setItem('one-wave-invitation-v1', JSON.stringify({ unlocked: true, accepted: true }))
    if (!localStorage.getItem('one-wave-invitation-v2')) localStorage.setItem('one-wave-invitation-v2', JSON.stringify({ score: 49 }))
  })
  await page.goto('/')
  await expect(page.getByText('Best of NE PROSTO POP', { exact: false })).toHaveCount(0)
  await expect(page.getByText('QAZAQCONCERT', { exact: false })).toHaveCount(0)
  await expect(page.getByText('19:00', { exact: false })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Смотреть второе видео: у меня есть идея' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Открыть игру, чтобы разблокировать второе видео' }).click()
  await expect(page.locator('video')).toHaveCount(0)
  await expect(page.getByText('Твой счёт: 49 / 50 ♡', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'Без спешки', exact: true }).click()
  await page.getByRole('button', { name: 'Начать мелодию', exact: true }).click()
  await page.getByRole('button', { name: 'Нота соль', exact: true }).click()
  await expect(page.getByTestId('game-won')).toHaveCount(0)
  await page.getByRole('button', { name: 'Нота до', exact: true }).click()
  await expect(page.getByTestId('game-won')).toBeVisible()
  await page.getByRole('button', { name: 'Посмотреть приглашение' }).click()
  await page.getByRole('button', { name: 'Моё видеоприглашение' }).click()
  const video = page.locator('video')
  await expect(video.locator('source')).toHaveAttribute('src', '/videos/your-invitation.mp4')
  await expect.poll(() => video.evaluate(e => e.readyState)).toBeGreaterThan(0)
  expect(await video.evaluate(e => e.duration)).toBeGreaterThan(85)
  await video.evaluate(e => e.play())
  await expect.poll(() => video.evaluate(e => e.currentTime)).toBeGreaterThan(.1)
  await page.getByRole('button', { name: 'Закрыть', exact: true }).click()
  await page.reload()
  await expect(page.getByRole('button', { name: 'Твоё приглашение' })).toBeVisible()
})

test('points survive closing and reloading but do not unlock early', async ({ page }) => {
  await installMediaClock(page)
  await page.goto('/')
  await page.getByRole('button', { name: 'У меня для тебя сюрприз' }).click()
  await page.getByRole('button', { name: 'Без спешки', exact: true }).click()
  await page.getByRole('button', { name: 'Начать мелодию', exact: true }).click()
  for (const lane of calmSequence.slice(0, 3)) await page.getByRole('button', { name: ['Нота до', 'Нота ми', 'Нота соль'][lane], exact: true }).click()
  await page.getByRole('button', { name: 'Закрыть', exact: true }).click()
  await page.reload()
  await expect(page.getByText('Best of NE PROSTO POP', { exact: false })).toHaveCount(0)
  await page.getByRole('button', { name: 'У меня для тебя сюрприз' }).click()
  await expect(page.getByText('Твой счёт: 3 / 50 ♡', { exact: false })).toBeVisible()
})
